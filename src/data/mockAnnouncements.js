// 카테고리별 필터링 함수
export const filterByCategory = (category) => {
  return mockAnnouncements.filter((a) => a.category.includes(category))
}

// 기관별 필터링 함수
export const filterByOrganization = (org) => {
  return mockAnnouncements.filter((a) => a.organization === org)
}

// 키워드 검색 함수
export const searchAnnouncements = (keyword) => {
  if (!keyword) return mockAnnouncements
  const lowerKeyword = keyword.toLowerCase()
  return mockAnnouncements.filter(
    (a) =>
      a.title.toLowerCase().includes(lowerKeyword) ||
      a.summary.toLowerCase().includes(lowerKeyword) ||
      a.organization.toLowerCase().includes(lowerKeyword) ||
      a.category.some((c) => c.toLowerCase().includes(lowerKeyword))
  )
}

// 마감일 기준 정렬 (임박순)
export const sortByDeadline = (announcements) => {
  return [...announcements].sort(
    (a, b) => new Date(a.deadline) - new Date(b.deadline)
  )
}

// 통계 정보
export const getStats = () => {
  const byCategory = {}
  const byOrganization = {}

  mockAnnouncements.forEach((a) => {
    a.category.forEach((c) => {
      byCategory[c] = (byCategory[c] || 0) + 1
    })
    byOrganization[a.organization] = (byOrganization[a.organization] || 0) + 1
  })

  return {
    total: mockAnnouncements.length,
    byCategory,
    byOrganization,
  }
}

export default mockAnnouncements
